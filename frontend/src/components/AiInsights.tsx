import { useState } from "react";
import { Sparkles, Loader2, Bot, FileText } from "lucide-react";
import { api, type InsightResult } from "../api";

export default function AiInsights({
  payload,
}: {
  payload: Record<string, unknown>;
}) {
  const [result, setResult] = useState<InsightResult | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);

  async function run() {
    setLoading(true);
    setError(null);
    try {
      setResult(await api.insights(payload));
    } catch (e) {
      setError((e as Error).message);
    } finally {
      setLoading(false);
    }
  }

  return (
    <div className="rounded-xl bg-gradient-to-br from-violet-900/20 to-slate-800/50 ring-1 ring-violet-700/40 p-4">
      <div className="flex flex-wrap items-center justify-between gap-2 mb-3">
        <div className="flex items-center gap-2">
          <Bot size={18} className="text-violet-300" />
          <h3 className="text-sm font-semibold text-slate-200">AI Insights</h3>
          <span className="text-xs text-slate-400">
            plain-English briefing from the numbers
          </span>
        </div>
        <button
          onClick={run}
          disabled={loading}
          className="inline-flex items-center gap-1.5 rounded-lg bg-violet-600 hover:bg-violet-500 disabled:opacity-60 px-3 py-1.5 text-xs font-medium text-white transition"
        >
          {loading ? (
            <Loader2 size={14} className="animate-spin" />
          ) : (
            <Sparkles size={14} />
          )}
          {result ? "Regenerate" : "Generate insights"}
        </button>
      </div>

      {error && <p className="text-sm text-red-400">Error: {error}</p>}

      {!result && !error && !loading && (
        <p className="text-sm text-slate-400">
          Click “Generate insights” for an AI-written summary of inventory health,
          revenue at risk, and what to reorder first.
        </p>
      )}

      {loading && (
        <p className="text-sm text-slate-400">Analyzing the dashboard…</p>
      )}

      {result && (
        <div className="space-y-2">
          <p className="text-sm text-slate-200 leading-relaxed whitespace-pre-line">
            {result.insight}
          </p>
          <div className="flex items-center gap-1.5 text-[11px] text-slate-500">
            {result.source === "claude" ? (
              <>
                <Bot size={12} /> Generated by Claude
              </>
            ) : (
              <>
                <FileText size={12} /> Rule-based summary · set ANTHROPIC_API_KEY
                for Claude-written insights
              </>
            )}
          </div>
        </div>
      )}
    </div>
  );
}
